export function getAllCategories(): StoreCategory[] {
  return CATEGORIES;
}

export function getCategoryBySlug(slug: string): StoreCategory | undefined {
  if (slug === "all") {
    return {
      slug: "all",
      name: "All Categories",
      icon: "LayoutGrid",
      image: "/images/hero-lifestyle.jpg",
      description: "Explore our complete collection of luxury products across all categories.",
      colorClass: "bg-emerald text-gold border-gold/30",
      badgeBg: "bg-emerald",
      badgeText: "text-emerald",
      department: "fashion-lifestyle",
      itemCount: PRODUCTS.length,
      subcategories: [
        { slug: "all", name: "All Subcategories" },
        { slug: "electronics", name: "Electronics" },
        { slug: "fashion", name: "Fashion" },
        { slug: "home-living", name: "Home & Living" },
        { slug: "beauty", name: "Beauty" },
        { slug: "sports", name: "Sports" },
        { slug: "toys-kids", name: "Toys & Kids" },
        { slug: "books", name: "Books" },
        { slug: "pet-supplies", name: "Pet Supplies" },
      ],
    };
  }

  // Handle department mappings
  if (slug === "beauty-skincare") return CATEGORIES.find((c) => c.slug === "beauty");
  if (slug === "electronics-gadgets") return CATEGORIES.find((c) => c.slug === "electronics");
  if (slug === "fashion-lifestyle") return CATEGORIES.find((c) => c.slug === "fashion");

  return CATEGORIES.find((c) => c.slug.toLowerCase() === slug.toLowerCase());
}

export const PRODUCTS: StoreProduct[] = RAW_PRODUCTS.map((p) => ({
  ...p,
  image: p.image ?? p.images[0],
  discountBadge: p.discountBadge ?? (p.discount ? `-${p.discount}%` : undefined),
  additionalImages: p.additionalImages ?? p.images.slice(1),
}));

export function getAllProducts(): StoreProduct[] {
  return PRODUCTS;
}

export function getProductById(id: string): StoreProduct | undefined {
  return PRODUCTS.find((p) => p.id === id || p.slug === id);
}

export function getProductsByCategory(categorySlug: string): StoreProduct[] {
  if (categorySlug === "all" || !categorySlug) return PRODUCTS;

  const cat = getCategoryBySlug(categorySlug);
  if (!cat) return [];

  return PRODUCTS.filter((p) => p.category === cat.slug);
}

export function getTopPicks(): StoreProduct[] {
  return PRODUCTS.slice(0, 5);
}

export function getDeals(): StoreProduct[] {
  return PRODUCTS.filter((p) => p.deal || (p.compareAtPrice && p.compareAtPrice > p.price));
}

export function getNewArrivals(): StoreProduct[] {
  return PRODUCTS.filter((p) => p.newArrival || p.featured);
}
